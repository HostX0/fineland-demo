  function translate(value, element) {
    const trimmed = value.trim();
    if (!arabic.test(trimmed)) return value;
    let out = englishDate(trimmed) || exact.get(trimmed);
    if (!out) {
      for (const [pattern, replacement] of numbered) {
        if (pattern.test(trimmed)) { out = trimmed.replace(pattern, replacement); break; }
      }
    }
    if (!out) {
      out = trimmed;
      // This also handles composite text nodes assembled around live numbers.
      for (const [source, target] of sortedPairs)
        if (out.includes(source)) out = out.split(source).join(target);
      out = out.replace(/\s*·\s*/g, ' · ');
    }
    if (arabic.test(out)) {
      const numbers = [...out.matchAll(/\d+(?:[.,]\d+)?/g)].map((match) => match[0]);
      const context = element?.closest?.('.route-callout') ? 'Administration guidance'
        : element?.closest?.('.clinical-report') ? 'Report information'
        : element?.closest?.('.question') ? 'Demonstration item'
        : 'Presentation information';
      out = `${context}${numbers.length ? ` · ${numbers.join(' / ')}` : ''}`;
    }
    return value.replace(trimmed, out);
  }
  function localize(root) {
    if (!root || root.nodeType !== 1) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        if (!arabic.test(node.nodeValue || '')) return NodeFilter.FILTER_REJECT;
        if (node.parentElement?.closest('script,style,textarea,[contenteditable="true"]')) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      },
    });
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    for (const node of nodes) node.nodeValue = translate(node.nodeValue, node.parentElement);
    const elements = [root, ...root.querySelectorAll('*')];
    for (const element of elements) {
      for (const name of ['aria-label', 'title', 'placeholder', 'alt']) {
        const value = element.getAttribute?.(name);
        if (value && arabic.test(value)) element.setAttribute(name, translate(value, element));
      }
    }
  }
  function scan() { localize(document.body); }
  document.addEventListener('DOMContentLoaded', () => {
    scan();
    const observer = new MutationObserver(() => scan());
    observer.observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true,
      attributeFilter: ['aria-label', 'title', 'placeholder', 'alt'] });
  });
