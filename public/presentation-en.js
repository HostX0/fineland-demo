  function englishDate(value) {
    const match = latinDigits(value.replace(/[\u200e\u200f\u061c]/g, '')).match(/^(\d{1,2})\s+(.+?)\s+(\d{4})$/);
    if (!match || !iraqiMonths.has(match[2])) return null;
    const date = new Date(Date.UTC(Number(match[3]), iraqiMonths.get(match[2]), Number(match[1])));
    return new Intl.DateTimeFormat('en-US', { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' }).format(date);
  }
